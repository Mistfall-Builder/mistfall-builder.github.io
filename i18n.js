  const DRAPEAUX = { fr: '🇫🇷', en: '🇬🇧', ru: '🇷🇺' };

  function detecter() {
    const force = localStorage.getItem(CLE);
    if (force && TEXTES[force]) return force;
    const nav = (navigator.languages || [navigator.language || 'en'])
      .map((l) => String(l).slice(0, 2).toLowerCase());
    for (const l of nav) if (TEXTES[l]) return l;
    return 'en';
  }

  let langue = detecter();

  /* {n} et compagnie sont remplacés ici plutôt que par concaténation : une
     phrase traduite ne place pas ses variables dans le même ordre qu'en
     français, et découper la phrase rendrait certaines traductions
     impossibles à écrire correctement. */
  function t(cle, vars) {
    let s = (TEXTES[langue] && TEXTES[langue][cle]);
    if (s === undefined) s = (TEXTES.en[cle] !== undefined ? TEXTES.en[cle] : cle);
    if (!vars) return s;
    return s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m));
  }

  /* LA MÊME PHRASE, MAIS DESTINÉE À innerHTML.
   *
   * `t` substitue ses variables telles quelles : c'est ce qu'il faut pour
   * textContent, title ou placeholder, où le navigateur ne lit pas de balises.
   * Injectée dans innerHTML, la même chaîne devient une porte d'entrée, car
   * plusieurs variables ne nous appartiennent pas — un pseudo, un nom de build
   * copié depuis la galerie, un message d'erreur renvoyé par le serveur.
   *
   * `tH` échappe les VARIABLES et laisse la phrase traduite intacte : les
   * traductions sont écrites par nous, les variables non. */
  function tH(cle, vars) {
    if (!vars) return t(cle);
    const propres = {};
    for (const [k, v] of Object.entries(vars)) {
      propres[k] = String(v == null ? '' : v).replace(/[&<>"']/g, (c) => (
        { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
    }
    return t(cle, propres);
  }

  function appliquer() {
    document.documentElement.lang = langue;
    for (const el of document.querySelectorAll('[data-i18n]')) {
      el.textContent = t(el.dataset.i18n);
    }
    for (const el of document.querySelectorAll('[data-i18n-ph]')) {
      el.placeholder = t(el.dataset.i18nPh);
    }
    for (const el of document.querySelectorAll('[data-i18n-title]')) {
      el.title = t(el.dataset.i18nTitle);
    }
  }

  window.I18N = {
    t,
    tH,
    appliquer,
    langues: Object.keys(TEXTES),
    drapeau: (l) => DRAPEAUX[l] || '🏳',
    nom: (l) => (TEXTES[l] ? TEXTES[l]['meta.langue'] : l),
    courante: () => langue,
    choisir(l) {
      if (!TEXTES[l]) return;
      langue = l;
      localStorage.setItem(CLE, l);
      appliquer();
      if (typeof window.surChangementDeLangue === 'function') {
        window.surChangementDeLangue();
      }
    },
  };
  window.t = t;
  window.tH = tH;
